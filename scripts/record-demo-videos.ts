/**
 * Reproducible demo-video recorder
 * ---------------------------------
 * Records short, silent, loopable MP4/WebM clips for every project demo
 * (cafe, calculator, library, student, bank, sneaker) so the Projects section
 * can show real video instead of only live animations.
 *
 * Why reproducible?
 * - Same viewport, same reduced-motion handling, same start state every run.
 * - No manual screen capture drift.
 * - Videos are committed to `public/videos/` and served statically.
 *
 * Usage:
 *   1. npm install -D playwright @playwright/test
 *   2. npx playwright install chromium
 *   3. npm run dev (in another terminal) OR let this script start it
 *   4. npx tsx scripts/record-demo-videos.ts
 *
 * Output:
 *   public/videos/
 *     chai-dosti-cafe.mp4
 *     responsive-calculator.mp4
 *     library-management-system.mp4
 *     student-management-system.mp4
 *     bank-management-system.mp4
 *     sneakerstore.mp4
 *     poster-*.jpg (fallback posters)
 *
 * The script is idempotent — re-running overwrites the same files.
 */

